#!/usr/bin/env python3
"""Import a lucide-static release into registry/lucide and regenerate
registry/src/lucide.rs.

Usage: scripts/update-lucide.py <extracted lucide-static package dir>

Fetch the package with `npm pack lucide-static@<version>` (or its tarball URL),
check its integrity against `npm view lucide-static@<version> dist.shasum`, and
extract it into an empty directory first. The script copies `icons/*.svg` and
`LICENSE`, removes icons the release dropped, and records the version from
`package.json`; `gpui-rhai update` then moves applications to it.
"""

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "registry" / "lucide"
SOURCE = ROOT / "registry" / "src" / "lucide.rs"
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    package = Path(sys.argv[1])
    version = json.loads((package / "package.json").read_text())["version"]
    # By name, as Rust compares `&str`: a binary search finds an icon.
    icons = sorted((package / "icons").glob("*.svg"), key=lambda icon: icon.stem.encode())
    names = [icon.stem for icon in icons]
    bad = [name for name in names if not NAME.match(name)]
    if bad:
        print(f"unexpected icon names: {bad[:10]}", file=sys.stderr)
        return 1

    TARGET.mkdir(parents=True, exist_ok=True)
    for stale in TARGET.glob("*.svg"):
        if stale.stem not in names:
            stale.unlink()
    for icon in icons:
        text = icon.read_text(encoding="utf-8")
        if "<script" in text or "href=" in text:
            print(f"{icon.name}: unexpected script or link", file=sys.stderr)
            return 1
        (TARGET / icon.name).write_text(text, encoding="utf-8")
    shutil.copyfile(package / "LICENSE", TARGET / "LICENSE")

    lines = [
        "// Generated by scripts/update-lucide.py from lucide-static; do not edit.",
        "",
        "/// The pinned Lucide release (`lucide-static` on npm).",
        f'pub const LUCIDE_VERSION: &str = "{version}";',
        "",
        "/// Lucide's license: ISC, and MIT for the icons derived from Feather.",
        'pub const LUCIDE_LICENSE: &str = include_str!("../lucide/LICENSE");',
        "",
        "/// Every Lucide icon by name, sorted, as `(name, svg)`.",
        "pub const LUCIDE_ICONS: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{name}", include_str!("../lucide/{name}.svg")),' for name in names]
    lines += ["];", ""]
    SOURCE.write_text("\n".join(lines), encoding="utf-8")
    print(f"lucide-static {version}: {len(names)} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
